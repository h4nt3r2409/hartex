func TestClaimRealtimeDeliveriesHonorsLeaseAndMode(t *testing.T) {
	d := notifyTestDB(t)
	ctx := context.Background()

	realtime := newTestChannel(t, d, notify.KindDingTalk, NotifyModeRealtime, `{}`)
	digest := newTestChannel(t, d, notify.KindDingTalk, NotifyModeDigest, `{}`)

	addTestEvent(t, d, notify.EventFindingCreated, 3001, notify.Snapshot{Severity: "high", VulnClass: "XSS"})
	if _, _, err := d.FanOutPendingEvents(ctx, 100); err != nil {
		t.Fatal(err)
	}

	// Realtime claiming should only get the row for the realtime channel and should not touch the digest channel's.
	got, err := d.ClaimRealtimeDeliveries(ctx, realtime.ID, 10, time.Minute)
	if err != nil {
		t.Fatalf("claim failed: %v", err)
	}
	if len(got) != 1 {
		t.Fatalf("want 1 claimed delivery, got %d", len(got))
	}
	if got[0].State != NotifyStateSending || got[0].Attempts != 1 {
		t.Fatalf("after claiming the state must be sending with attempts=1, got state=%s attempts=%d", got[0].State, got[0].Attempts)
	}
	// The joined rendering context must be complete (channel config + event snapshot + finding id).
	if got[0].Channel == nil || len(got[0].Channel.Config) == 0 {
		t.Fatal("the claimed delivery is missing channel config, so rendering would fail")
	}
	if got[0].FindingID != 3001 {
		t.Fatalf("the finding id was not carried over from the event, got %d", got[0].FindingID)
	}

	// The lease has not expired, so a second claim should return nothing — this is the guarantee that "the same row is not
	// delivered by two dispatchers at once."
	again, err := d.ClaimRealtimeDeliveries(ctx, realtime.ID, 10, time.Minute)
	if err != nil {
		t.Fatal(err)
	}
	if len(again) != 0 {
		t.Fatalf("must not re-claim during the lease, got %d", len(again))
	}

	// Deliveries for the digest channel should not be touched by realtime claiming.
	left, err := d.ClaimRealtimeDeliveries(ctx, digest.ID, 10, time.Minute)
	if err != nil {
		t.Fatal(err)
	}
	if len(left) != 0 {
		t.Fatalf("realtime claiming must not take digest-channel deliveries, got %d", len(left))
	}
}

