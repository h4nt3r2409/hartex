// TestSaveNotificationChannelKeepsExplicitZeroRate locks down a place that was once written incorrectly:
// **0 is a valid configuration meaning "no rate limit" and must not be treated by the db layer as "unspecified" and overwritten with a default.**
//
// Historical bug: SaveNotificationChannel contained `if RatePerMin <= 0 { take default value }`,
// so docs, UI hints, and takeTokens all interpreted "0 = unlimited," yet the database-write layer alone silently changed it to
// 20 (DingTalk/WeCom/Telegram) or 100 (Feishu) — the operator thought they had lifted the limit while actually being throttled,
// with no indication at all. The distinction between "unspecified" and "explicit 0" can only be expressed in the request body,
// so the default is filled in at the server layer (see notifyCreateChannel), and the db layer only stores it.
func TestSaveNotificationChannelKeepsExplicitZeroRate(t *testing.T) {
	d := notifyTestDB(t)
	ctx := context.Background()

	// Explicit 0 (unlimited): must be stored as-is.
	unlimited := &NotificationChannel{
		Name: "no rate limit", Kind: notify.KindDingTalk, RatePerMin: 0,
		Config: json.RawMessage(`{"webhook":"https://example.com/h"}`),
	}
	id, err := d.SaveNotificationChannel(ctx, unlimited)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { d.Exec(`DELETE FROM notification_channels WHERE id=$1`, id) })
	got, err := d.NotificationChannelByID(ctx, id)
	if err != nil {
		t.Fatal(err)
	}
	if got.RatePerMin != 0 {
		t.Fatalf("an explicit 0 means no rate limit and must be stored as-is, got %d", got.RatePerMin)
	}
	if got.Mode != NotifyModeRealtime {
		t.Fatalf("the default mode must be realtime, got %s", got.Mode)
	}

	// A negative value is invalid input and should be rejected rather than silently changed to something else.
	bad := &NotificationChannel{
		Name: "negative rate limit", Kind: notify.KindDingTalk, RatePerMin: -1,
		Config: json.RawMessage(`{"webhook":"https://example.com/h"}`),
	}
	if _, err := d.SaveNotificationChannel(ctx, bad); err == nil {
		t.Fatal("a negative rate limit must be rejected")
	}
}

